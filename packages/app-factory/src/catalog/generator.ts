import type { AppArchetype, BlueprintFile } from '../types/app-types.js';

export interface GeneratedFile {
  path: string;
  content: string;
  kind: BlueprintFile['kind'];
}

export interface GenerateOptions {
  applicationId: string;
  name: string;
  /** Inject a defect for the auto-fix benchmark/tests (missing tests). */
  injectDefects?: boolean;
  /** Inject a hard-coded secret to prove the security gate blocks it. */
  injectSecret?: boolean;
}

export function generateProject(
  archetype: AppArchetype,
  options: GenerateOptions,
): GeneratedFile[] {
  switch (archetype) {
    case 'abap-debugger':
      return generateAbap(options);
    case 'restaurant-app':
      return generateRestaurant(options);
    case 'ai-app-builder':
      return generateAiBuilder(options);
    default:
      return generateGeneric(options);
  }
}

