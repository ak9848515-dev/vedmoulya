function applyDefects(files: GeneratedFile[], options: GenerateOptions): GeneratedFile[] {
  let result = files;
  if (options.injectDefects) {
    // Drop one test file so the auto-fix path is exercised.
    result = result.filter((f) => !f.path.includes('.test.'));
  }
  if (options.injectSecret) {
    result = result.map((f) =>
      f.path === 'src/index.ts'
        ? {
            ...f,
            content: `${f.content}\n// TODO: remove\nconst SECRET_TOKEN = "sk-live-abcdef0123456789abcdef";\n`,
          }
        : f,
    );
  }
  return result;
}

function file(path: string, content: string, kind: BlueprintFile['kind']): GeneratedFile {
  return { path, content, kind };
}
