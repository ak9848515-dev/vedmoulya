// ─────────────────────────────────────────────────────────────────────────────
// VedMoulya — Mission: USER-SCOPED provider credentials (PROVIDER-01 → Mission)
//
// The contradiction this locks down: a provider the user connected (stored,
// verified credential) was CONNECTED+ACTIVE in the Providers UI while Mission
// honestly reported WAITING_FOR_PROVIDER — because Mission only ever saw
// adapters registered from the DEPLOYMENT environment.
//
// These tests prove the narrow user-scoped seam:
//   - availability is evaluated against the OWNER's orchestrator;
//   - one user's adapter is never visible to another user;
//   - the platform orchestrator still serves availability when no user scope
//     is supplied (existing behavior preserved);
//   - the required-capability predicate is unchanged;
//   - execution uses the OWNER's agent/orchestrator, so generation really runs
//     on the adapter built from the user's own credential.
// ─────────────────────────────────────────────────────────────────────────────

