import { describe, it, expect, vi, beforeEach } from 'vitest';

import { ContentAgencyApplicationService } from '../ContentAgencyApplicationService.js';
import { InMemoryContentAgencyRepository } from '../InMemoryContentAgencyRepository.js';
import { ContentAgencyAIService } from '../ContentAgencyAIService.js';
import type { AIOrchestrationService } from '../../ai/AIOrchestrationService.js';

const aiResponse = {
  content: '# Draft content\n\nOn-brand copy generated by the pipeline.',
  provider: 'mock',
  model: 'mock-standard',
  qualityScore: 8,
  traceId: 'trace_1',
  tokenUsage: { input: 120, output: 340, total: 460 },
  cost: 0.0042,
  latency: 42,
};

function makeService(overrides: { orchestrate?: unknown } = {}) {
  const repo = new InMemoryContentAgencyRepository();
  const aiMock = {
    orchestrate:
      overrides.orchestrate instanceof Error
        ? vi.fn().mockRejectedValue(overrides.orchestrate)
        : vi.fn().mockResolvedValue(overrides.orchestrate ?? aiResponse),
  } as unknown as AIOrchestrationService;
  const ai = new ContentAgencyAIService(aiMock);
  const svc = new ContentAgencyApplicationService(repo, ai);
  return { svc, repo, aiMock };
}

const USER = 'user-1';

const clientInput = {
  company: 'Acme Inc',
  industry: 'SaaS',
  brandVoice: 'bold and helpful',
  targetAudience: 'CTOs of mid-size companies',
  products: ['Acme Analytics', 'Acme Sync'],
  services: ['Implementation', 'Support'],
  goals: ['Increase demo bookings', 'Shorten sales cycle'],
  website: 'https://acme.example',
  socialLinks: { linkedin: 'https://linkedin.com/company/acme' },
};

describe('ContentAgencyApplicationService — clients', () => {
  it('creates a client with defaults and timestamps', async () => {
    const { svc } = makeService();
    const res = await svc.createClient(USER, clientInput);
    expect(res.success).toBe(true);
    expect(res.data?.company).toBe('Acme Inc');
    expect(res.data?.industry).toBe('SaaS');
    expect(res.data?.products).toEqual(['Acme Analytics', 'Acme Sync']);
    expect(res.data?.createdAt).toBeDefined();
    expect(res.data?.userId).toBe(USER);
  });

  it('rejects empty company name', async () => {
    const { svc } = makeService();
    const res = await svc.createClient(USER, { company: '  ' });
    expect(res.success).toBe(false);
    expect(res.error).toMatch(/company/i);
  });

  it('lists, updates and deletes clients scoped to the user', async () => {
    const { svc } = makeService();
    const created = await svc.createClient(USER, clientInput);
    const id = created.data!.id;

    const listed = await svc.listClients(USER);
    expect(listed.data).toHaveLength(1);

    const otherUser = await svc.getClient('other-user', id);
    expect(otherUser.success).toBe(false);

    const updated = await svc.updateClient(USER, id, { industry: 'Fintech' });
    expect(updated.data?.industry).toBe('Fintech');

    const deleted = await svc.deleteClient(USER, id);
    expect(deleted.success).toBe(true);
    expect((await svc.listClients(USER)).data).toHaveLength(0);
  });
});

